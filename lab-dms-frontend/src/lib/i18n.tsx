const dictionaries: Record<Lang, Record<string, string>> = { pt, en };

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'pt',
  setLang: () => {},
  t: (key) => key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem('lab_dms_lang');
    return stored === 'en' || stored === 'pt' ? stored : 'pt';
  });

  const setLang = useCallback((newLang: Lang) => {
    localStorage.setItem('lab_dms_lang', newLang);
    setLangState(newLang);
  }, []);

  const t = useCallback(
    (key: string) => dictionaries[lang][key] ?? dictionaries.pt[key] ?? key,
    [lang]
  );

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

/** Formats a date according to the current language. */
export function formatDate(value: string | number | Date, lang: Lang, withTime = true): string {
  const date = new Date(value);
  return date.toLocaleString(lang === 'pt' ? 'pt-BR' : 'en-US', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    ...(withTime ? { hour: '2-digit', minute: '2-digit' } : {}),
  });
}
